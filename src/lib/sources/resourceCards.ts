function camelKey(name: string): string {
  const parts = name.split(/[^A-Za-z0-9]+/).filter(Boolean)
  return parts
    .map((p, i) => (i === 0 ? p.toLowerCase() : p[0].toUpperCase() + p.slice(1).toLowerCase()))
    .join('')
}

function buildSet(set: string, cardNames: readonly string[]): Source[] {
  return cardNames.map((n) => resourceCard(set, camelKey(n), n))
}

export const oreCardSources = buildSet('ore', ORE_CARD_NAMES)
export const barCardSources = buildSet('bar', BAR_CARD_NAMES)
export const veinCardSources = buildSet('vein', VEIN_CARD_NAMES)
export const starCardSources = buildSet('star', STAR_CARD_NAMES)
