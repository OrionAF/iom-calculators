import type { Source } from '$lib/engine/types'

/**
 * Per-resource cards (ores, bars, veins, stars, fish), generated from the
 * Cards wiki dump. Each card multiplies only ITS resource's gain, and the
 * multiplier is uniform per set (Standard 1.5x / Gilded 2x / Polychrome =
 * polychrome_card_bonus_* stat / Infernal = combinedCardMultiplier with the
 * set's infernal_card_bonus_* stat), so these sources carry no fn values —
 * they exist to TRACK card levels (0 unowned … 4 Infernal). Card counts for
 * runtime inputs (cardsOwned, polyCardCount, infernal*Cards,
 * totalInfernalCards) are derived from these levels via deriveCardCounts()
 * in formulas/cardMath.ts.
 */

const resourceCard = (set: string, key: string, name: string): Source => ({
  key: `cards.${set}.${key}`,
  name: `Card: ${name}`,
  system: 'cards',
  maxLevel: 4,
  fn: () => 0,
  inputs: [],
})

